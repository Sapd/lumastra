<script lang="ts">
    import { onMount, onDestroy } from 'svelte';
    import { apiGet } from '$lib/api/client.js';
    import { runSSEBus } from '$lib/stores/run-sse-bus.js';
    import {
        ClusterStatusResponseSchema,
        type ClusterNode,
    } from '$lib/schemas/api-admin-responses.js';
    import { clusterNodeName } from '$lib/utils/admin/cluster-node-name.js';
    import InfoRailCard from '$lib/components/admin/InfoRailCard.svelte';
    import * as m from '$lib/paraglide/messages.js';

    const POLL_INTERVAL_MS = 15_000;

    let nodes = $state<ClusterNode[]>([]);
    // Registered (expected) nodes; `nodes` is the LIVE list only.
    let totalRegistered = $state(0);
    let loaded = $state(false);
    let loadFailed = $state(false);
    let pollTimer: ReturnType<typeof setInterval> | undefined;
    let unsubSSE: (() => void) | undefined;
    let sseVersion = $state(0);
    let disposed = false;

    async function loadCluster(): Promise<void> {
        const { data } = await apiGet('/api/admin/cluster', ClusterStatusResponseSchema);
        if (disposed) return;
        if (data) {
            nodes = data.nodes;
            totalRegistered = data.totalRegistered;
        }
        // A failed fetch is not "no servers"; keep the last good list if any.
        loadFailed = !data;
        loaded = true;
    }

    // Current load per node = active/pending/cancelling runs it owns, live via
    // the SSE bus (no extra endpoint — a pure client-side join, same approach
    // NodeSnapshotSchema's doc comment describes for Mission Control's node
    // panel). A plain object (not a Map) — this is a fresh, non-mutated
    // snapshot recomputed on every dependency change, not persisted reactive
    // state, so it doesn't need SvelteMap's fine-grained reactivity.
    let loadByInstance = $derived.by((): Record<string, number> => {
        void sseVersion;
        const counts: Record<string, number> = {};
        for (const run of runSSEBus.activeRuns) {
            if (!run.ownerInstanceId) continue;
            counts[run.ownerInstanceId] = (counts[run.ownerInstanceId] ?? 0) + 1;
        }
        return counts;
    });

    onMount(() => {
        void loadCluster();
        pollTimer = setInterval(() => void loadCluster(), POLL_INTERVAL_MS);
        unsubSSE = runSSEBus.onAnyChange(() => {
            sseVersion += 1;
        });
    });

    onDestroy(() => {
        disposed = true;
        if (pollTimer) clearInterval(pollTimer);
        unsubSSE?.();
    });
</script>

<!--
  Single-node installs — the common self-hosted case — get nothing here: one
  real node plus an "auto-generated name" apology is noise, not information,
  and the full roster is one click away at Cluster. Only collapse away once
  loaded (loading briefly still shows the card) and only for exactly one
  node — 0 nodes is a real signal (cluster tracking looks broken) and 2+ is
  the genuinely-multi-node case this rail exists for.
-->
{#if !loaded || loadFailed || nodes.length !== 1 || totalRegistered > 1}
    <InfoRailCard
        id="runs-servers"
        title={m.admin_runs_rail_servers_title()}
        linkHref="/admin/system/health#cluster"
        linkLabel={m.admin_runs_rail_servers_link()}>
        {#if !loaded}
            <p class="text-xs text-surface-500">{m.loading_default()}</p>
        {:else if loadFailed && nodes.length === 0}
            <p class="text-xs text-red-300">{m.route_admin_cluster_load_error()}</p>
        {:else if nodes.length === 0}
            <p class="text-xs italic text-surface-500">{m.admin_runs_rail_servers_empty()}</p>
        {:else}
            <ul class="space-y-1.5">
                {#each nodes as node (node.instanceId)}
                    {@const name = clusterNodeName(node.instanceId, node.hostname)}
                    <li class="flex items-center gap-2 text-xs">
                        <span class="inline-block h-1.5 w-1.5 shrink-0 rounded-full bg-green-400"
                        ></span>
                        <span
                            class="min-w-0 flex-1 truncate font-mono text-surface-300"
                            title={name.isAutoGenerated
                                ? `${node.instanceId} — ${m.admin_runs_server_unnamed_hint()}`
                                : node.instanceId}>
                            {name.label}
                            {#if name.isAutoGenerated}
                                <span class="text-surface-600" aria-hidden="true">*</span>
                            {/if}
                        </span>
                        <span class="shrink-0 tabular-nums text-surface-500">
                            <!-- Live load, not a total: "web-1 · 0 runs" beside a list of
                                 1,437 runs per task read as a contradiction. -->
                            {m.admin_runs_server_running_now({
                                count: (loadByInstance[node.instanceId] ?? 0).toLocaleString(),
                            })}
                        </span>
                    </li>
                {/each}
            </ul>
            {#if totalRegistered > nodes.length}
                <p class="mt-1.5 text-[11px] text-amber-300">
                    {m.route_admin_cluster_not_responding({
                        count: totalRegistered - nodes.length,
                    })}
                </p>
            {/if}
            {#if nodes.some((n) => clusterNodeName(n.instanceId, n.hostname).isAutoGenerated)}
                <p class="mt-1.5 text-[10px] text-surface-600">
                    * {m.admin_runs_server_unnamed_hint()}
                </p>
            {/if}
        {/if}
    </InfoRailCard>
{/if}
