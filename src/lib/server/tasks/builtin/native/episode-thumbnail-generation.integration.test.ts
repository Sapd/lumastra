it('holds proportional sibling ordering stable from recapture until publication commits', async () => {
    await sql`UPDATE media_file_items SET start_offset_ms=NULL,end_offset_ms=NULL WHERE file_id=${file}`;
    await sql`UPDATE media_items SET episode_number=1 WHERE id=${episode}`;
    await sql`UPDATE media_items SET episode_number=2 WHERE id=${sibling}`;
    await deleteArtworkById(sql, oldCandidate);
    const barrier = postgres(getTestDatabaseUrl(), { max: 1 });
    const editor = postgres(getTestDatabaseUrl(), { max: 1 });
    let release: () => void = () => {};
    let ready: () => void = () => {};
    const released = new Promise<void>((resolve) => {
        release = resolve;
    });
    const locked = new Promise<void>((resolve) => {
        ready = resolve;
    });
    const holder = barrier.begin(async (tx) => {
        // Reads and row locks still work; the first publication write after
        // recapture must wait here, creating a deterministic race boundary.
        await tx`LOCK TABLE image_candidates IN SHARE MODE`;
        ready();
        await released;
    });
    await locked;
    const publishing = cycle();
    try {
        await vi.waitFor(async () => {
            const waiting = await sql`SELECT 1 FROM pg_stat_activity
                WHERE datname=current_database() AND wait_event_type='Lock'
                  AND query LIKE '%DELETE FROM image_candidates alias USING%'`;
            expect(waiting.length).toBeGreaterThan(0);
        });
        await expect(
            editor.begin(async (tx) => {
                await tx`SET LOCAL lock_timeout='100ms'`;
                await tx`UPDATE media_items SET episode_number=0 WHERE id=${sibling}`;
            }),
        ).rejects.toMatchObject({ code: '55P03' });
        expect(
            (await sql`SELECT episode_number FROM media_items WHERE id=${sibling}`)[0]
                .episode_number,
        ).toBe(2);
    } finally {
        release();
        await holder;
        await barrier.end();
        await editor.end();
    }
    expect((await publishing).itemsProcessed).toBe(1);
    expect(
        await sql`SELECT id FROM image_candidates WHERE media_item_id=${episode}
        AND provider='frame-extract' AND selected`,
    ).toHaveLength(1);
    await sql`UPDATE media_items SET episode_number=0 WHERE id=${sibling}`;
});
