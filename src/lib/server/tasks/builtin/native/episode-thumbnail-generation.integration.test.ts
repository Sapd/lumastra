it.each([
    'window',
    'generation',
    'default',
    'bytes',
    'physical',
    'manual',
    'provider',
    'suppression',
    'path-suppression',
    'cancel',
] as const)('rejects a late %s change before retiring or publishing candidates', async (change) => {
    const controller = new AbortController();
    mocks.generate.mockImplementationOnce(async ({ outputPath }: { outputPath: string }) => {
        await writeFile(outputPath, 'late generated bytes');
        if (change === 'window')
            await sql`UPDATE media_file_items SET end_offset_ms=590000 WHERE media_item_id=${episode}`;
        if (change === 'default')
            await sql`DELETE FROM media_file_items WHERE media_item_id=${episode}`;
        if (change === 'generation')
            await sql`UPDATE media_items SET media_segment_generation=gen_random_uuid() WHERE id=${episode}`;
        if (change === 'bytes')
            await sql`UPDATE media_files SET file_hash_head='source-b' WHERE id=${file}`;
        if (change === 'physical')
            await writeFile(join(directory, 'Current - S01E01E02.mkv'), 'changed physical input');
        if (change === 'provider')
            await sql`UPDATE image_candidates SET provider='tmdb',provider_ref='/explicit.jpg',remote_url='provider:tmdb' WHERE id=${oldCandidate}`;
        if (change === 'manual')
            await sql`UPDATE image_candidates SET chosen_by='admin',locked=true WHERE id=${oldCandidate}`;
        if (change === 'suppression')
            await sql`INSERT INTO image_provider_suppressions(owner,provider,role) VALUES (${episode},'frame-extract','thumb')`;
        if (change === 'path-suppression')
            await sql`INSERT INTO media_artwork_suppressions(media_item_id,artwork_type,file_path) VALUES (${episode},'thumb',${outputPath})`;
        if (change === 'cancel') controller.abort();
        return { success: true, bestEffort: false };
    });
    const result = await cycle(controller.signal);
    expect(result.itemsProcessed).toBe(0);
    expect(await sql`SELECT id FROM image_candidates WHERE id=${oldCandidate}`).toHaveLength(1);
    expect(
        await sql`SELECT id FROM image_candidates WHERE media_item_id=${episode} AND provider='frame-extract'`,
    ).toHaveLength(0);
    if (change === 'generation')
        expect(
            (
                await sql`SELECT id FROM image_candidates WHERE media_item_id=${episode} AND selected`
            )[0].id,
        ).toBe(oldCandidate);
    expect(await readFile(oldPath, 'utf8')).toBe('original sidecar bytes');
});
