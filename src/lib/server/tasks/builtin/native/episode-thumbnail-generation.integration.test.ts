async function prepareOrdinaryOwner(): Promise<{ legitimate: { id: string }; otherFile: string }> {
    await writeFile(join(directory, 'Fictional - S01E01E02.mkv'), 'authoritative separate input');
    oldPath = join(directory, 'Fictional - S01E01E02-thumb.jpg');
    await writeFile(oldPath, 'original sidecar bytes');
    await sql`UPDATE image_candidates SET file_path=${oldPath},provider_ref=${oldPath} WHERE id=${oldCandidate}`;
    const ownVideo = join(directory, 'First.mkv');
    await writeFile(ownVideo, 'first separate input');
    await sql`UPDATE media_files SET file_path=${ownVideo} WHERE id=${file}`;
    const otherFile = randomUUID();
    extraFiles.push(otherFile);
    await sql`INSERT INTO media_files(id,file_path,duration_seconds) VALUES (${otherFile},${join(directory, 'Fictional - S01E01E02.mkv')},1200)`;
    await sql`UPDATE media_file_items SET start_offset_ms=NULL,end_offset_ms=NULL WHERE media_item_id=${episode}`;
    await sql`UPDATE media_file_items SET file_id=${otherFile},start_offset_ms=NULL,end_offset_ms=NULL WHERE media_item_id=${sibling}`;
    await sql`DELETE FROM image_candidates WHERE media_item_id=${sibling}`;
    await upsertLocalArtwork(sql, {
        mediaItemId: sibling,
        artworkType: 'thumb',
        filePath: oldPath,
    });
    const [legitimate] =
        await sql`SELECT id FROM image_candidates WHERE media_item_id=${sibling} AND selected`;
    return { legitimate: { id: legitimate.id }, otherFile };
}

