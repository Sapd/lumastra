import { beforeEach, expect, it, vi } from 'vitest';
import { probeLiveTvFeed } from './source-probe';
const { fetchFeed } = vi.hoisted(() => ({ fetchFeed: vi.fn() }));
vi.mock('./fetch-source.js', () => ({
    fetchSsrfValidatedText: fetchFeed,
    M3U_MAX_FETCH_BYTES: 268435456,
    XMLTV_MAX_FETCH_BYTES: 104857600,
}));
vi.mock('$lib/server/utils/logger.js', () => ({ Logger: { for: () => ({}) } }));
beforeEach(() => {
    fetchFeed.mockReset();
});
it.each([
    '<?xml version="1.0"?><tv source-info-name="Provider"></tv><!-- generated by provider -->',
    '<tv/> <!-- empty guide --> <!-- updated today -->',
])('accepts an XMLTV document with a legal epilog: %s', async (content) => {
    fetchFeed.mockResolvedValue(content);
    expect(await probeLiveTvFeed('http://provider.example/epg', 'XMLTV')).toBeUndefined();
});
it('does not accept an HTML login document containing a tv element', async () => {
    fetchFeed.mockResolvedValue('<html><tv></tv></html>');
    expect(await probeLiveTvFeed('http://provider.example/epg', 'XMLTV')).toContain('XMLTV');
});
