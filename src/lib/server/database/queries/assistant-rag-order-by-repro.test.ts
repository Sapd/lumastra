/**
 * Repro test for F2 — RAG vector query lacks ORDER BY on distance.
 *
 * Finding: findRelevantMediaByVector uses LIMIT 500 but no
 * ORDER BY embedding <=> vec ASC. PostgreSQL returns an arbitrary 500-row
 * sample; JavaScript re-sorts them in memory and slices top-15. As the
 * embedding table grows, true nearest neighbors are increasingly likely to
 * lie outside the sampled set.
 *
 * Citations: src/lib/server/database/queries/assistant-rag.queries.ts:137-149,
 *            src/routes/api/assistant/+server.ts:259-265
 */

import { describe, it, expect } from 'vitest';
import { toUserId } from '$lib/shared/user-id.js';
import { unrestrictedAccess } from './builders/media-access-boundary.js';

describe('F2 — RAG vector query missing ORDER BY on distance', () => {
    it('the SQL fragment from findRelevantMediaByVector does not contain ORDER BY', async () => {
        const { findRelevantMediaByVector } =
            await import('$lib/server/database/queries/assistant-rag.queries.js');

        // Capture the SQL string generated by the function.
        // Since postgres.js template tags execute immediately, we need to
        // intercept the query. We pass a mock sql that records the query text.
        let capturedQuery = '';
        const mockSql = Object.assign(
            (strings: TemplateStringsArray, ...values: unknown[]) => {
                capturedQuery = strings.reduce((acc, str, i) => {
                    const val = values[i] ?? '';
                    return acc + str + (typeof val === 'string' ? `'${val}'` : String(val));
                }, '');
                return Promise.resolve([]);
            },
            {
                json: (v: unknown) => v,
                unsafe: (v: string) => v,
            },
        ) as unknown as import('postgres').Sql;

        try {
            await findRelevantMediaByVector(mockSql, {
                queryEmbeddingStr: '[0.1,0.2,0.3]',
                userId: toUserId('aaaaaaaa-0000-0000-0000-000000000001'),
                access: unrestrictedAccess(),
            });
        } catch {
            // We only care about the captured SQL
        }

        // The query should contain LIMIT 500 (the bug is about the missing ORDER BY)
        expect(capturedQuery).toContain('LIMIT');

        // BUG: There is no ORDER BY clause on the vector distance operation.
        // The function relies on in-memory JavaScript sorting of an arbitrary
        // 500-row sample from Postgres, which defeats the HNSW index and
        // returns semantically wrong results at scale.
        // Note: There IS an ORDER BY inside the lateral join subquery for
        // provider metadata priority, but there is NO ORDER BY on the vector
        // similarity (e.g. `me.embedding <=> ...`).
        expect(capturedQuery.toLowerCase()).not.toContain('order by me.embedding');
        expect(capturedQuery.toLowerCase()).not.toContain('order by similarity');
    });

    it('JavaScript in-memory sort is performed instead of database ORDER BY', async () => {
        // Reproduce the client-side sort from the assistant route (lines 259-265)
        const fakeMovies = [
            { title: 'A', similarity: 0.9 },
            { title: 'B', similarity: 0.1 },
            { title: 'C', similarity: 0.5 },
        ];

        const sorted = fakeMovies
            .map((m) => ({ ...m, similarity: Number(m.similarity ?? 0) }))
            .sort((a, b) => a.similarity - b.similarity)
            .slice(0, 15);

        // This proves the application expects to re-sort in JS because the
        // DB query did not order by distance. The first item is the LEAST
        // similar (0.1) because that's the default Postgres sort order
        // without ORDER BY — arbitrary.
        expect(sorted[0].similarity).toBe(0.1);
        expect(sorted[sorted.length - 1].similarity).toBe(0.9);
    });
});
