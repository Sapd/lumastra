/**
 * Escape HTML characters so a string is inert text inside markup or an
 * attribute. Use it on every value interpolated into an HTML-bearing i18n
 * message (`<span class="…">{title}</span>`).
 */
export function escapeHtml(str: string): string {
    return str
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#039;');
}
