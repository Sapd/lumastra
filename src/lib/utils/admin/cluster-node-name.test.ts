import { describe, it, expect } from 'vitest';
import { clusterNodeName } from './cluster-node-name.js';

describe('clusterNodeName', () => {
    it('shows a pinned INSTANCE_ID verbatim', () => {
        expect(clusterNodeName('web-1', 'container-abc123')).toEqual({
            label: 'web-1',
            isAutoGenerated: false,
        });
    });

    it('detects the auto-generated hostname+suffix fallback', () => {
        const result = clusterNodeName('web-host-a1b2c3', 'web-host');
        expect(result.isAutoGenerated).toBe(true);
        expect(result.label).toBe('#a1b2c3');
    });

    it('is case-insensitive on the suffix (base36 fallback can include digits/letters)', () => {
        const result = clusterNodeName('MyHost-9zx3q1', 'MyHost');
        expect(result.isAutoGenerated).toBe(true);
        expect(result.label).toBe('#9zx3q1');
    });

    it('does not false-positive on a pinned id that merely contains a hyphen', () => {
        const result = clusterNodeName('worker-general', 'somehost');
        expect(result.isAutoGenerated).toBe(false);
        expect(result.label).toBe('worker-general');
    });

    it('does not false-positive when the suffix is not exactly 6 chars', () => {
        const result = clusterNodeName('web-host-abc', 'web-host');
        expect(result.isAutoGenerated).toBe(false);
        expect(result.label).toBe('web-host-abc');
    });

    it('handles a hostname containing regex special characters safely', () => {
        const result = clusterNodeName('web.host+1-a1b2c3', 'web.host+1');
        expect(result.isAutoGenerated).toBe(true);
        expect(result.label).toBe('#a1b2c3');
    });

    it('treats an empty hostname as never auto-generated', () => {
        const result = clusterNodeName('a1b2c3', '');
        expect(result.isAutoGenerated).toBe(false);
    });
});
