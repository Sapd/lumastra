/**
 * Admin IA redesign, spec §3.4: Cluster nodes show a friendly name
 * (`INSTANCE_ID`) when the operator pinned one; when unset, the node falls
 * back to `${hostname}-${6-char random suffix}` (see
 * `resolveInstanceId`/`generateFallbackInstanceId` in `$lib/server/config.ts`). That fallback shape is
 * deterministic, so it can be detected client-side from the two fields the
 * cluster API already returns (`instanceId`, `hostname`) — no new server
 * field/schema bump needed.
 */

/** Matches `${hostname}-` followed by exactly 6 lowercase alphanumerics —
 *  the fallback suffix shape (`crypto.randomUUID().slice(0, 6)` or
 *  `Math.random().toString(36).slice(2, 8)`). */
function isAutoGeneratedSuffix(instanceId: string, hostname: string): boolean {
    if (!hostname) return false;
    const escaped = hostname.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    return new RegExp(`^${escaped}-[a-z0-9]{6}$`, 'i').test(instanceId);
}

export interface ClusterNodeName {
    /** What to display as the node's name. */
    label: string;
    /** True when `instanceId` looks like the unpinned auto-generated fallback. */
    isAutoGenerated: boolean;
}

/**
 * Resolves the friendly display name for a cluster node. An explicitly-set
 * `INSTANCE_ID` (anything not matching the auto-generated shape) is shown
 * verbatim; an auto-generated one is shortened to its random suffix
 * (`#a1b2c3`) so the noisy hostname-prefixed id doesn't dominate the card —
 * callers should pair this with a hint to set `INSTANCE_ID`.
 */
export function clusterNodeName(instanceId: string, hostname: string): ClusterNodeName {
    if (isAutoGeneratedSuffix(instanceId, hostname)) {
        const suffix = instanceId.slice(instanceId.length - 6);
        return { label: `#${suffix}`, isAutoGenerated: true };
    }
    return { label: instanceId, isAutoGenerated: false };
}
