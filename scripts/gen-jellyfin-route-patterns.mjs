/**
 * Regenerates src/lib/routing/jellyfin-route-patterns.ts: the /j route patterns
 * the reroute hook matches case-insensitively (Jellyfin's ASP.NET routing is
 * case-insensitive; SvelteKit's is not).
 *
 * The table is plain strings so the AGPL reroute hook never imports the
 * proprietary route tree. Without that tree (an AGPL-only build) it is simply
 * empty. `src/lib/routing/reroute-pathname.test.ts` fails when it is stale.
 *
 * Run: `node scripts/gen-jellyfin-route-patterns.mjs` (from the application root).
 */

import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = join(dirname(fileURLToPath(import.meta.url)), '..');
export const JELLYFIN_ROUTE_DIR = join(APP, 'src/routes/(proprietary)/j');
export const PATTERNS_FILE = join(APP, 'src/lib/routing/jellyfin-route-patterns.ts');

/** Every `/j` route directory holding a `+server.ts`, as `/Items/[itemId]`-style patterns. */
export function collectJellyfinRoutePatterns(dir = JELLYFIN_ROUTE_DIR) {
    if (!existsSync(dir)) return [];
    const out = [];
    (function walk(d) {
        for (const e of readdirSync(d)) {
            const p = join(d, e);
            if (statSync(p).isDirectory()) walk(p);
            else if (e === '+server.ts') out.push(d.slice(dir.length) || '/');
        }
    })(dir);
    // The bare 404 catch-all would match everything; it carries no casing.
    return out.filter((p) => p !== '/[...path]').sort();
}

export function renderPatternsFile(patterns) {
    return `// SPDX-FileCopyrightText: 2026 Denis Arnst (Sapd)
// SPDX-License-Identifier: AGPL-3.0-only

// GENERATED by scripts/gen-jellyfin-route-patterns.mjs — do not edit by hand.
// The /j route patterns, matched case-insensitively by reroute-pathname.ts.
// Plain strings: the AGPL reroute hook must not import the proprietary tree.

export const JELLYFIN_ROUTE_PATTERNS: readonly string[] = [
${patterns.map((p) => `    '${p}',`).join('\n')}
];
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
    const patterns = collectJellyfinRoutePatterns();
    writeFileSync(PATTERNS_FILE, renderPatternsFile(patterns));
    console.log(`wrote ${patterns.length} patterns to ${PATTERNS_FILE.slice(APP.length + 1)}`);
}
